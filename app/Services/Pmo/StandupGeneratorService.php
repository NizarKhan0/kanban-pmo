<?php

declare(strict_types=1);

namespace App\Services\Pmo;

use App\Models\BoardColumn;
use App\Models\Task;
use Illuminate\Support\Carbon;
use Illuminate\Support\Str;

/**
 * Builds the Daily Standup Report as clean text, ready to paste into
 * WhatsApp / Telegram ("chat": *bold* markers) or email ("plain").
 */
final class StandupGeneratorService
{
    public const FORMAT_CHAT = 'chat';

    public const FORMAT_PLAIN = 'plain';

    /** @var array<string, string> */
    public const FORMATS = [
        self::FORMAT_CHAT => 'WhatsApp / Telegram',
        self::FORMAT_PLAIN => 'Email / Plain Text',
    ];

    public function __construct(
        private readonly BoardColumnService $columns,
        private readonly TaskService $tasks,
        private readonly ActivityLogger $activity,
    ) {}

    public function generate(?TaskFilters $filters = null, string $format = self::FORMAT_CHAT, bool $includeNotes = true): string
    {
        $chat = $format !== self::FORMAT_PLAIN;
        $bold = static fn (string $text): string => $chat ? "*{$text}*" : Str::upper($text);
        $filters ??= new TaskFilters;
        // Report order always follows the board's manual order.
        $filters = new TaskFilters(...[...$filters->toArray(), 'sort' => 'manual']);

        $tz = (string) config('pmo.timezone', 'Asia/Kuala_Lumpur');
        $now = Carbon::now($tz);
        $board = $this->tasks->board($filters);
        $columns = $this->columns->list();

        $all = collect($board)->flatten(1);
        $total = $all->count();
        $done = $all->filter(fn (Task $t): bool => $t->isCompleted())->count();
        $overdue = $all->filter(fn (Task $t): bool => $t->isOverdue())->count();
        $rate = $total === 0 ? 0 : (int) round($done / $total * 100);

        $lines = [];
        $lines[] = ($chat ? '📋 ' : '').$bold('Daily Standup Report');
        $lines[] = $now->format('l, j F Y');
        $lines[] = 'Prepared by: '.$this->activity->actorName();
        if ($filters->narrows()) {
            $lines[] = 'Scope: '.$this->describeScope($filters);
        }
        $lines[] = '';
        $lines[] = ($chat ? '📊 ' : '')."Summary: {$total} ".Str::plural('task', $total)." · {$done} done ({$rate}%) · {$overdue} overdue";

        foreach ($columns as $column) {
            $cards = $board[$column->id] ?? collect();

            $lines[] = '';
            $lines[] = ($chat ? $column->icon.' ' : '').$bold($column->name)." ({$cards->count()})";

            if ($cards->isEmpty()) {
                $lines[] = '• No cards';

                continue;
            }

            foreach ($cards as $task) {
                $lines[] = $this->taskLine($task, $column);

                if ($task->notes !== null && ! $column->is_done_column) {
                    $lines[] = '   ↳ Blocker / Notes: '.Str::limit(Str::squish($task->notes), 140);
                }
            }
        }

        if ($includeNotes) {
            $notes = $this->activity->todaysNotes();

            if ($notes->isNotEmpty()) {
                $lines[] = '';
                $lines[] = ($chat ? '📝 ' : '').$bold('Notes');
                foreach ($notes as $note) {
                    $time = $note->created_at?->copy()->setTimezone($tz)->format('H:i');
                    $lines[] = "• {$note->task_title} — {$note->actor_name}".($time ? ", {$time}" : '');
                }
            }
        }

        $lines[] = '';
        $lines[] = '— Generated by Kanban PMO at '.$now->format('H:i');

        return implode("\n", $lines);
    }

    private function taskLine(Task $task, BoardColumn $column): string
    {
        $parts = [];

        if ($pic = $task->picLabel()) {
            $parts[] = $task->teamMember === null ? "{$pic} (former PIC)" : $pic;
        }
        if ($project = $task->projectLabel()) {
            $parts[] = $project;
        }
        if ($task->due_date !== null && ! $column->is_done_column) {
            $parts[] = 'Due '.$task->due_date->format('j M');
        }

        [$doneSubs, $totalSubs] = $task->subtaskCounts();
        if ($totalSubs > 0) {
            $parts[] = "{$doneSubs}/{$totalSubs} subtasks";
        }

        $prefix = $task->isOverdue() ? '[OVERDUE] ' : '';
        $priority = ! $column->is_done_column && $task->priority === 'high' ? ' (High)' : '';

        return '• '.$prefix.$task->title.$priority.($parts === [] ? '' : ' — '.implode(' · ', $parts));
    }

    private function describeScope(TaskFilters $filters): string
    {
        $scope = [TaskFilters::VIEWS[$filters->view] ?? 'Kanban Board'];

        if (trim($filters->search) !== '') {
            $scope[] = 'search "'.trim($filters->search).'"';
        }
        if ($filters->priority !== '') {
            $scope[] = (Task::PRIORITIES[$filters->priority] ?? $filters->priority).' priority';
        }
        if ($filters->due !== 'any') {
            $scope[] = TaskFilters::DUE[$filters->due] ?? $filters->due;
        }
        if ($filters->project !== '' || $filters->assignee !== '') {
            $scope[] = 'project / assignee filter';
        }

        return implode(', ', $scope);
    }
}
